export interface BookSeoPage {
  slug: string;
  code: BookSeoCode;
  grade: number;
  bookNumber: 1 | 2;
  bookLabel: string;
  semesterLabel: string;
  title: string;
  metaDescription: string;
  outline: string;
  cover: string;
}

function selectSemesterContent(outline: string, semester?: 1 | 2): string {
  if (!semester) return outline;

  const result: string[] = [];
  let includeItems = false;

  for (const line of outline.split(/\r?\n/)) {
    if (line === 'Daftar Isi Buku') {
      result.push(line);
    } else if (line === 'Semester 1' || line === 'Semester 2') {
      includeItems = line === `Semester ${semester}`;
      if (includeItems) result.push(line);
    } else if (line === 'Karakter yang Ditanamkan') {
      includeItems = true;
      result.push(line);
    } else if (line.startsWith('- ') && includeItems) {
      result.push(line);
    }
  }

  return result.join('\n\n');
}

function makeMetaDescription(title: string, outline: string): string {
  const firstTopic = outline.split(/\r?\n/).find((line) => line.startsWith('- '))?.slice(2);
  const text = firstTopic ? `${title}. ${firstTopic}` : title;
  if (text.length <= 160) return text;

  const prefix = text.slice(0, 157);
  const lastSpace = prefix.lastIndexOf(' ');
  return `${prefix.slice(0, lastSpace > 0 ? lastSpace : prefix.length)}…`;
}

export function getBookSeoPath(code: BookSeoCode, grade: number, bookNumber: 1 | 2 = 1): string {
  if (code === 'mtk') return `/buku/matematika-kelas-${grade}/`;
  if (code === 'bind') return `/buku/bahasa-indonesia-kelas-${grade}/`;
  return `/buku/ipas-kelas-${grade}-buku-${bookNumber === 1 ? 'a' : 'b'}/`;
}

